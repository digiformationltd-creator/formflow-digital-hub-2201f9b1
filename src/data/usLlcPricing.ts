export const getUsLlcPricingByCode = (code: string): UsLlcStatePricing | undefined => {
  if (!code) return undefined;
  return US_LLC_STATE_PRICING.find((s) => s.state_code.toUpperCase() === code.toUpperCase());
};

export const getPopularUsLlcPricing = (): UsLlcStatePricing[] => {
  return US_LLC_STATE_PRICING.filter((s) => s.is_popular);
};

export const formatUSD = (n: number) =>
  new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", maximumFractionDigits: 0 }).format(n);
